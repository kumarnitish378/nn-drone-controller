"""Generate the model headers of the C++ flight library (ardupilot/libraries/AP_NNControl/models/NN_Model_<frame>.h)
from the shipped networks. Weights are written transposed, [outputs][inputs], so each neuron's row is contiguous
for the dot products on the flight controller."""
from pathlib import Path

from nn_drone.export.model_package import flight_network_arrays
from nn_drone.paths import DEFAULT_WEIGHTS, REPOSITORY_ROOT
from nn_drone.simulation.config import IntegratorSettleRule

CPP_LIBRARY_DIR = REPOSITORY_ROOT / "ardupilot" / "libraries" / "AP_NNControl"
CPP_MODELS_DIR = CPP_LIBRARY_DIR / "models"
VALUES_PER_LINE = 8
SUPPORTED_HISTORY_FRAMES = 2


def model_header(frame, weights_path):
    info, arrays = flight_network_arrays(weights_path)
    profile = info.profile
    if not (profile.has_integrator_input and profile.has_mass_class_input and profile.history_frames == SUPPORTED_HISTORY_FRAMES
            and profile.integrator.settle_rule is IntegratorSettleRule.VEHICLE_AND_TARGET_STILL):
        raise ValueError(f"{weights_path}: simulator profile {profile.name} has an input layout the C++ library does not build")
    timing, integrator = profile.control_timing, profile.integrator
    namespace = f"nn_model_{frame}"
    layer_count = len(arrays) // 2
    lines = [f"// Generated by `python -m nn_drone export-cpp` from models/{Path(weights_path).name}. Do not edit.",
             "// Include it in one .cpp file only: the arrays are defined here.",
             "#pragma once", "", '#include "../NN_Model.h"', "", f"namespace {namespace} {{", ""]
    layer_entries = []
    for index in range(layer_count):
        weights, bias = arrays[f"pi_W{index}"], arrays[f"pi_b{index}"]
        inputs, outputs = weights.shape
        lines += _array(f"layer{index}_weights", weights.T.reshape(-1), f"[{outputs} * {inputs}]")
        lines += _array(f"layer{index}_bias", bias.reshape(-1), f"[{outputs}]")
        layer_entries.append(f"        {{layer{index}_weights, layer{index}_bias, {inputs}, {outputs}}},")
    lines += ["static const NN_Model model = {",
              f'    "{frame}",', f'    "{profile.name}",', f"    {info.motor_count},",
              f"    {_float(timing.period_s)},", f"    {'true' if timing.scales_with_size else 'false'},",
              "    {", *layer_entries, "    },",
              f"    {{{_float(integrator.capture_radius)}, {_float(integrator.clamp)}, {_float(integrator.input_scale)}, "
              f"{_float(integrator.settled_speed)}, {_float(integrator.still_target_speed)}, {_float(integrator.target_jump_speed)}}},",
              "};", "", f"}}  // namespace {namespace}", ""]
    return "\n".join(lines)


def _float(value):
    """A float literal C++ accepts: 1 -> 1.0f (\"1f\" is not valid)."""
    text = f"{float(value):.9g}"
    if not any(mark in text for mark in ".en"):
        text += ".0"
    return text + "f"


def _array(name, values, dimensions):
    lines = [f"NN_WEIGHTS_SECTION NN_WEIGHTS_ALIGNMENT static const float {name}{dimensions} = {{"]
    for start in range(0, len(values), VALUES_PER_LINE):
        lines.append("    " + ", ".join(_float(value) for value in values[start:start + VALUES_PER_LINE]) + ",")
    return lines + ["};", ""]


def export_cpp_models(output_dir=CPP_MODELS_DIR):
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for frame, weights_path in DEFAULT_WEIGHTS.items():
        path = output_dir / f"NN_Model_{frame}.h"
        path.write_text(model_header(frame, weights_path), encoding="utf-8", newline="\n")
        written.append(path)
    return written
